MAX_TOOLS = int(load_config().llm.get("max_tools", 16))


def default_box() -> ToolBox:
    cfg = load_config()
    cfg["mcp_servers"] = None        # the benchmark is about Jarvis's own tools, and stays offline
    return ToolBox(cfg, {})


def every_tool_box() -> ToolBox:
    """The default tools plus the optional ones (Google, ask_claude, PowerShell), as if all were set up."""
    box = default_box()
    disabled = set((box.cfg.get("tools") or {}).get("disabled") or [])
    box.tools.update({n: t for n, t in registry._TOOLS.items() if n not in disabled})
    return box


def run(box, cases, previous=()):
    """[(request, expected alternatives, picked)] for the cases whose tools this box has."""
    out = []
    for case in cases:
        prev, (request, expected) = (case[0], case[1:]) if len(case) == 3 else (previous, case)
        needs = [alt.split("|") for alt in expected.split()]
        needs = [[n for n in alt if n in box.tools] for alt in needs]
        if not all(needs):
            continue                     # a tool this PC doesn't have
        out.append((request, needs, prev, tool_select.pick(box, request, prev, max_tools=MAX_TOOLS)))
    return out



def misses(results):
    return [(req, prev, [alt for alt in needs if not set(alt) & set(picked)], picked)
            for req, needs, prev, picked in results if any(not set(alt) & set(picked) for alt in needs)]


class ToolPickBenchmark(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.box = default_box()

    def report(self, name, results):
        sizes = [len(p) for *_, p in results]
        if os.environ.get("JARVIS_PICK_VERBOSE") or "-v" in sys.argv:
            print(f"\n{name}: {len(results)} requests, mean {statistics.mean(sizes):.2f} tools, max {max(sizes)}")
        return sizes

    def test_benchmark_is_big_and_covers_every_tool(self):
        self.assertGreaterEqual(len(CASES) + len(FOLLOW_UPS), 150)
        named = {n for _, exp in CASES + OPTIONAL_CASES for n in exp.replace("|", " ").split()}
        named |= {n for _, _, exp in FOLLOW_UPS for n in exp.replace("|", " ").split()}
        self.assertEqual(set(self.box.tools) - named, set(), "tools with no benchmark request")
        self.assertEqual(named - set(registry._TOOLS), set(), "benchmark names a tool that doesn't exist")

    def test_every_needed_tool_is_offered(self):
        results = run(self.box, CASES) + run(self.box, FOLLOW_UPS)
        sizes = self.report("default tools", results)
        self.assertEqual(misses(results), [])
        self.assertLessEqual(max(sizes), MAX_TOOLS)
        self.assertLessEqual(statistics.mean(sizes), 8)

    def test_optional_tools_too(self):
        box = every_tool_box()
        results = run(box, CASES + OPTIONAL_CASES) + run(box, FOLLOW_UPS)
        sizes = self.report("every tool switched on", results)
        self.assertEqual(misses(results), [])
        self.assertLessEqual(statistics.mean(sizes), 8)

    def test_offered_tools_would_be_allowed_to_run(self):
        # a tool whose trigger words the request lacks is refused when called, so offering it is pointless
        for request, needs, prev, picked in run(self.box, CASES) + run(self.box, FOLLOW_UPS):
            for name in picked:
                self.assertTrue(self.box.get(name).allowed_for(request), f"{request!r}: {name}")
            for alt in needs:
                self.assertTrue(any(self.box.get(n).allowed_for(request) for n in alt), f"{request!r}: {alt}")

    def test_the_right_tool_ranks_high(self):
        # broad words ("open", "what's") must not bury the tool that fits; it should be near the top
        for request, needs, prev, picked in run(self.box, CASES):
            if len(needs) == 1:
                rank = min(picked.index(n) for n in needs[0] if n in picked)
                self.assertLess(rank, 3, f"{request!r}: {needs[0]} at {rank} in {picked}")

    def test_small_talk_gets_no_tools(self):
        for request in SMALL_TALK:
            self.assertEqual(tool_select.pick(self.box, request), [], request)

    def test_remember_only_when_asked(self):
        requests = [c[0] for c in CASES] + [c[1] for c in FOLLOW_UPS] + SMALL_TALK + [
            "what's my favourite colour", "my favourite colour is", "write a note that the meeting moved",
            "what colour should I paint the lights", "where did I park", "I'm allergic to peanuts"]
        for request in requests:
            asked = any(w in request.lower() for w in REMEMBER_WORDS)
            self.assertEqual("remember" in tool_select.pick(self.box, request), asked, request)

    def test_fast_enough_to_run_on_every_request(self):
        box = every_tool_box()
        tool_select.pick(box, "warm up the index")
        requests = [c[0] for c in CASES]
        t0 = time.perf_counter()
        for request in requests:
            tool_select.pick(box, request)
        per_request_ms = (time.perf_counter() - t0) * 1000 / len(requests)
        self.assertLess(per_request_ms, 5, f"{per_request_ms:.2f} ms per request")


